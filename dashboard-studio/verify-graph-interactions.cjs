const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');

(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1536,height:1080}});
 const errors=[],writes=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',request=>{if(request.method()!=='GET')writes.push(request.method())});
 await page.goto('http://127.0.0.1:8035/workspace.html');
 const node=page.locator('.c-node.assumption').first();
 const id=await node.getAttribute('data-node');
 const connectedPaths=page.locator(`.c-link[data-from="${id}"],.c-link[data-to="${id}"]`);
 const scale=locator=>locator.evaluate(el=>{const matrix=new DOMMatrix(getComputedStyle(el).transform);return Math.hypot(matrix.a,matrix.b)});
 const mark=node.locator('.c-node-mark');
 assert.equal(await scale(mark),1);
 await node.hover();
 await page.waitForFunction(id=>{
  const node=document.querySelector(`[data-node="${id}"]`);
  const mark=node.querySelector('.c-node-mark');
  const links=[...document.querySelectorAll(`.c-link[data-from="${id}"],.c-link[data-to="${id}"]`)];
  return node.classList.contains('preview')&&new DOMMatrix(getComputedStyle(mark).transform).a>1.2&&links.every(link=>parseFloat(getComputedStyle(link).strokeWidth)>3);
 },id);
 assert(await connectedPaths.count()>0);
 assert(await connectedPaths.evaluateAll(links=>links.every(link=>link.classList.contains('preview')&&parseFloat(getComputedStyle(link).strokeWidth)>3)));
 assert(await page.locator('.c-node.connected').count()>0);
 const anchor=await node.boundingBox();
 await node.click();
 await page.mouse.move(5,5);
 assert.equal(await node.getAttribute('aria-pressed'),'true');
 assert(await connectedPaths.evaluateAll(links=>links.every(link=>link.classList.contains('highlight'))));
 assert.deepEqual(await node.boundingBox(),anchor,'Selection keeps the graph anchored');
 assert((await page.locator('.c-inspector').innerText()).includes(id));
 await page.locator('.c-viewport').screenshot({path:path.join(__dirname,'graph-selected.png')});
 await node.click();
 await page.mouse.move(5,5);
 assert.equal(await node.getAttribute('aria-pressed'),'false');
 assert.equal(await page.locator('.c-link.highlight,.c-link.preview').count(),0);
 await page.keyboard.press('Tab');
 await node.focus();
 assert(await node.evaluate(el=>el.matches(':focus-visible')));
 assert(await connectedPaths.evaluateAll(links=>links.every(link=>link.classList.contains('preview'))));
 await page.keyboard.press('Space');
 assert.equal(await node.getAttribute('aria-pressed'),'true');
 assert.equal(await page.evaluate(()=>document.activeElement.dataset.node),id,'Keyboard activation retains focus');
 await page.keyboard.press('Space');
 assert.equal(await node.getAttribute('aria-pressed'),'false');
 const provision=page.locator('.c-node.covenant').first();
 await provision.hover();
 await page.waitForFunction(()=>{
  const el=document.querySelector('.c-node.covenant.preview .c-node-mark');
  if(!el)return false;
  const m=new DOMMatrix(getComputedStyle(el).transform);
  return Math.hypot(m.a,m.b)>1.2&&m.a>0&&m.b>0;
 });
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await mark.evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
 assert.equal(await connectedPaths.first().evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
 await page.mouse.move(5,5);
 const historyNode=page.locator('[data-ph-event="B01-D01"]');
 const historyMark=historyNode.locator('.ph-node-mark');
 const historyPathIds=(await historyNode.getAttribute('data-ph-paths')).split(' ');
 await historyNode.hover();
 assert(await scale(historyMark)>1.1);
 assert(await page.locator('.ph-path-emphasis').evaluateAll((paths,ids)=>paths.length>0&&paths.every(path=>ids.includes(path.dataset.phPath)),historyPathIds));
 await historyNode.click();
 await page.mouse.move(5,5);
 assert.equal(await historyNode.getAttribute('aria-pressed'),'true');
 assert(await scale(historyMark)>1.1);
 assert(await page.locator('.ph-path-selected').evaluateAll((paths,ids)=>paths.length>0&&paths.every(path=>ids.includes(path.dataset.phPath)&&parseFloat(getComputedStyle(path).strokeWidth)>2.6),historyPathIds));
 assert.equal(await page.locator('.ph-event-selected').count(),1);
 await page.keyboard.press('Tab');
 const pendingEvent=page.locator('[data-ph-event="B01-D03"]');
 await pendingEvent.focus();
 assert(await pendingEvent.evaluate(el=>el.matches(':focus-visible')));
 await page.keyboard.press('Space');
 assert.equal(await page.evaluate(()=>document.activeElement.dataset.phEvent),'B01-D03','History activation retains keyboard focus');
 assert.equal(await pendingEvent.getAttribute('aria-pressed'),'true');
 const proposal=page.locator('.ph-proposed-line');
 assert((await proposal.getAttribute('class')).includes('ph-path-selected'));
 assert.notEqual(await proposal.evaluate(el=>getComputedStyle(el).strokeDasharray),'none','Pending paths stay dashed');
 assert.equal(await historyMark.evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
 await page.locator('.ph-section').screenshot({path:path.join(__dirname,'history-interactive.png')});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.goto('http://127.0.0.1:8035/workspace.html');
 const mobileNode=mobile.locator('.c-node.assumption').first();
 await mobileNode.tap();
 assert.equal(await mobileNode.getAttribute('aria-pressed'),'true');
 await mobileNode.tap();
 assert.equal(await mobileNode.getAttribute('aria-pressed'),'false');
 assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+2));
 assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);
 await browser.close();
 console.log('Both graphs passed: hover enlarges marks and connected paths, click selection persists, evidence toggles off, anchors stay fixed, keyboard focus survives activation, pending paths stay dashed, touch and reduced motion work.');
})().catch(error=>{console.error(error);process.exit(1)});
